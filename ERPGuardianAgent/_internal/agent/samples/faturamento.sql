CREATE OR REPLACE PACKAGE BODY PKG_FATURAMENTO AS

  PROCEDURE GERAR_NOTA_FISCAL(p_pedido_id IN NUMBER) IS
  BEGIN
    -- Simulação de processo crítico de NF-e
    UPDATE ESTOQUE SET SALDO = SALDO - 1 WHERE PRODUTO_ID = (SELECT PRODUTO_ID FROM PEDIDOS WHERE ID = p_pedido_id);
    
    INSERT INTO NOTAS_FISCAIS (PEDIDO_ID, DATA_EMISSAO, STATUS)
    VALUES (p_pedido_id, SYSDATE, 'PROCESSANDO');
    
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;
  END;

END PKG_FATURAMENTO;
